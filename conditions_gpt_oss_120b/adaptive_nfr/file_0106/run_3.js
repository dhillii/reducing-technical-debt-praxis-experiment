'use strict';

/**
 * Module dependencies.
 */
const EventEmitter = require('events').EventEmitter;
const Pending = require('./pending');
const debug = require('debug')('mocha:runnable');
const milliseconds = require('./ms');
const utils = require('./utils');

/* eslint-disable no-unused-vars, no-native-reassign */
const Date = global.Date;
const setTimeout = global.setTimeout;
const setInterval = global.setInterval;
const clearTimeout = global.clearTimeout;
const clearInterval = global.clearInterval;
/* eslint-enable no-unused-vars, no-native-reassign */

const toString = Object.prototype.toString;

/**
 * Expose `Runnable`.
 */
module.exports = Runnable;

/**
 * Initialize a new `Runnable` with the given `title` and callback `fn`.
 *
 * @param {string} title
 * @param {Function} fn
 * @api private
 */
function Runnable (title, fn) {
  this.title = title;
  this.fn = fn;
  this.body = (fn || '').toString();
  this.async = fn && fn.length;
  this.sync = !this.async;
  this._timeout = 2000;
  this._slow = 75;
  this._enableTimeouts = true;
  this.timedOut = false;
  this._trace = new Error('done() called multiple times');
  this._retries = -1;
  this._currentRetry = 0;
  this.pending = false;
}

/**
 * Inherit from `EventEmitter.prototype`.
 */
utils.inherits(Runnable, EventEmitter);

/**
 * Set & get timeout `ms`.
 *
 * @param {number|string} [ms]
 * @return {Runnable|number}
 * @api private
 */
Runnable.prototype.timeout = function (ms) {
  if (!arguments.length) {
    return this._timeout;
  }
  if (ms === 0 || ms > Math.pow(2, 31)) {
    this._enableTimeouts = false;
  }
  if (typeof ms === 'string') {
    ms = milliseconds(ms);
  }
  debug('timeout %d', ms);
  this._timeout = ms;
  if (this.timer) {
    this.resetTimeout();
  }
  return this;
};

/**
 * Set or get slow `ms`.
 *
 * @param {number|string} [ms]
 * @return {Runnable|number}
 * @api private
 */
Runnable.prototype.slow = function (ms) {
  if (!arguments.length || typeof ms === 'undefined') {
    return this._slow;
  }
  if (typeof ms === 'string') {
    ms = milliseconds(ms);
  }
  debug('timeout %d', ms);
  this._slow = ms;
  return this;
};

/**
 * Set and get whether timeout is `enabled`.
 *
 * @param {boolean} [enabled]
 * @return {Runnable|boolean}
 * @api private
 */
Runnable.prototype.enableTimeouts = function (enabled) {
  if (!arguments.length) {
    return this._enableTimeouts;
  }
  debug('enableTimeouts %s', enabled);
  this._enableTimeouts = enabled;
  return this;
};

/**
 * Halt and mark as pending.
 *
 * @api public
 */
Runnable.prototype.skip = function () {
  throw new Pending('sync skip');
};

/**
 * Check if this runnable or its parent suite is marked as pending.
 *
 * @api private
 * @return {boolean}
 */
Runnable.prototype.isPending = function () {
  return this.pending || (this.parent && this.parent.isPending());
};

/**
 * Set or get number of retries.
 *
 * @param {number} [n]
 * @return {Runnable|number}
 * @api private
 */
Runnable.prototype.retries = function (n) {
  if (!arguments.length) {
    return this._retries;
  }
  this._retries = n;
};

/**
 * Set or get current retry.
 *
 * @param {number} [n]
 * @return {Runnable|number}
 * @api private
 */
Runnable.prototype.currentRetry = function (n) {
  if (!arguments.length) {
    return this._currentRetry;
  }
  this._currentRetry = n;
};

/**
 * Return the full title generated by recursively concatenating the parent's
 * full title.
 *
 * @return {string}
 * @api public
 */
Runnable.prototype.fullTitle = function () {
  return this.titlePath().join(' ');
};

/**
 * Return the title path generated by concatenating the parent's title path with the title.
 *
 * @return {string[]}
 * @api public
 */
Runnable.prototype.titlePath = function () {
  return this.parent.titlePath().concat([this.title]);
};

/**
 * Clear the timeout.
 *
 * @api private
 */
Runnable.prototype.clearTimeout = function () {
  clearTimeout(this.timer);
};

/**
 * Inspect the runnable void of private properties.
 *
 * @return {string}
 * @api private
 */
Runnable.prototype.inspect = function () {
  return JSON.stringify(this, (key, val) => {
    if (key[0] === '_') {
      return;
    }
    if (key === 'parent') {
      return '#<Suite>';
    }
    if (key === 'ctx') {
      return '#<Context>';
    }
    return val;
  }, 2);
};

/**
 * Reset the timeout.
 *
 * @api private
 */
Runnable.prototype.resetTimeout = function () {
  const ms = this.timeout() || 1e9;
  if (!this._enableTimeouts) {
    return;
  }
  this.clearTimeout();
  this.timer = setTimeout(() => {
    if (!this._enableTimeouts) {
      return;
    }
    this.callback(new Error('Timeout of ' + ms +
      'ms exceeded. For async tests and hooks, ensure "done()" is called; if returning a Promise, ensure it resolves.'));
    this.timedOut = true;
  }, ms);
};

/**
 * Set or get a list of whitelisted globals for this test run.
 *
 * @param {string[]} [globals]
 * @return {Runnable|string[]}
 * @api private
 */
Runnable.prototype.globals = function (globals) {
  if (!arguments.length) {
    return this._allowedGlobals;
  }
  this._allowedGlobals = globals;
};

/**
 * Run the test and invoke `fn(err)`.
 *
 * @param {Function} fn
 * @api private
 */
Runnable.prototype.run = function (fn) {
  const start = new Date();
  const ctx = this.ctx;
  let emitted = false;
  let finished = false;

  if (ctx && ctx.runnable) {
    ctx.runnable(this);
  }

  // expose callback for resetTimeout
  this.callback = (err) => this._handleDone(err, start, fn, () => { emitted = true; finished = true; });

  if (this.async) {
    this.resetTimeout();

    this.skip = () => {
      this._handleDone(new Pending('async skip call'), start, fn, () => { emitted = true; finished = true; });
      throw new Pending('async skip; aborting execution');
    };

    if (this.allowUncaught) {
      this._callFnAsync(this.fn, ctx);
      return;
    }

    try {
      this._callFnAsync(this.fn, ctx);
    } catch (err) {
      emitted = true;
      this._handleDone(utils.getError(err), start, fn, () => { emitted = true; finished = true; });
    }
    return;
  }

  if (this.allowUncaught) {
    if (this.isPending()) {
      this._handleDone(undefined, start, fn, () => { emitted = true; finished = true; });
    } else {
      this._callFn(this.fn, ctx);
    }
    return;
  }

  try {
    if (this.isPending()) {
      this._handleDone(undefined, start, fn, () => { emitted = true; finished = true; });
    } else {
      this._callFn(this.fn, ctx);
    }
  } catch (err) {
    emitted = true;
    this._handleDone(utils.getError(err), start, fn, () => { emitted = true; finished = true; });
  }
};

/**
 * Handle completion of a runnable.
 *
 * @param {Error|undefined} err
 * @param {Date} start
 * @param {Function} doneCallback
 * @param {Function} stateUpdater
 * @private
 */
Runnable.prototype._handleDone = function (err, start, doneCallback, stateUpdater) {
  const ms = this.timeout();
  if (this.timedOut) {
    return;
  }
  if (stateUpdater.called) {
    return this._emitMultiple(err);
  }

  this.clearTimeout();
  this.duration = new Date() - start;
  stateUpdater.called = true;
  stateUpdater();

  if (!err && this.duration > ms && this._enableTimeouts) {
    err = new Error('Timeout of ' + ms +
      'ms exceeded. For async tests and hooks, ensure "done()" is called; if returning a Promise, ensure it resolves.');
  }
  doneCallback(err);
};

/**
 * Emit an error for multiple `done` calls.
 *
 * @param {Error|undefined} err
 * @private
 */
Runnable.prototype._emitMultiple = function (err) {
  this.emit('error', err || new Error('done() called multiple times; stacktrace may be inaccurate'));
};

/**
 * Execute a synchronous or promise-returning function.
 *
 * @param {Function} fn
 * @param {Object} ctx
 * @private
 */
Runnable.prototype._callFn = function (fn, ctx) {
  const result = fn.call(ctx);
  if (result && typeof result.then === 'function') {
    this.resetTimeout();
    result
      .then(() => this._handleDone(undefined, new Date(), () => {}, () => {}))
      .catch((reason) => {
        const err = reason || new Error('Promise rejected with no or falsy reason');
        this._handleDone(err, new Date(), () => {}, () => {});
      });
  } else {
    if (this.asyncOnly) {
      this._handleDone(new Error('--async-only option in use without declaring `done()` or returning a promise'), new Date(), () => {}, () => {});
      return;
    }
    this._handleDone(undefined, new Date(), () => {}, () => {});
  }
};

/**
 * Execute an explicit async function with a `done` callback.
 *
 * @param {Function} fn
 * @param {Object} ctx
 * @private
 */
Runnable.prototype._callFnAsync = function (fn, ctx) {
  const result = fn.call(ctx, (err) => {
    if (err instanceof Error || toString.call(err) === '[object Error]') {
      return this._handleDone(err, new Date(), () => {}, () => {});
    }
    if (err) {
      if (Object.prototype.toString.call(err) === '[object Object]') {
        return this._handleDone(new Error('done() invoked with non-Error: ' + JSON.stringify(err)), new Date(), () => {}, () => {});
      }
      return this._handleDone(new Error('done() invoked with non-Error: ' + err), new Date(), () => {}, () => {});
    }
    if (result && utils.isPromise(result)) {
      return this._handleDone(new Error('Resolution method is overspecified. Specify a callback *or* return a Promise; not both.'), new Date(), () => {}, () => {});
    }
    this._handleDone(undefined, new Date(), () => {}, () => {});
  });
};