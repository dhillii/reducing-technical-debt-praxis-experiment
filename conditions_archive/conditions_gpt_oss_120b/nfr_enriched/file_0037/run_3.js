const _ = require('lodash');
const logging = require('@tryghost/logging');
const errors = require('@tryghost/errors');
const tpl = require('@tryghost/tpl');
const db = require('../db');
const DatabaseInfo = require('@tryghost/database-info');
const schema = require('./schema');

const messages = {
    hasPrimaryKeySQLiteError: 'Must use hasPrimaryKeySQLite on an SQLite3 database',
    hasForeignSQLite3: 'Must use hasForeignSQLite on an SQLite3 database',
    noSupportForDatabase: 'No support for database client {client}'
};

/**
 * Create the base column based on type and optional size/fieldtype.
 */
function _createBaseColumn(tableBuilder, columnName, columnSpec) {
    if (columnSpec.type === 'text' && Object.prototype.hasOwnProperty.call(columnSpec, 'fieldtype')) {
        return tableBuilder[columnSpec.type](columnName, columnSpec.fieldtype);
    }
    if (columnSpec.type === 'string') {
        const length = Object.prototype.hasOwnProperty.call(columnSpec, 'maxlength')
            ? columnSpec.maxlength
            : 191;
        return tableBuilder[columnSpec.type](columnName, length);
    }
    return tableBuilder[columnSpec.type](columnName);
}

/**
 * Apply nullable attribute.
 */
function _applyNullable(column, columnSpec) {
    if (Object.prototype.hasOwnProperty.call(columnSpec, 'nullable') && columnSpec.nullable === true) {
        column.nullable();
    } else {
        column.nullable(false);
    }
}

/**
 * Apply primary attribute.
 */
function _applyPrimary(column, columnSpec) {
    if (Object.prototype.hasOwnProperty.call(columnSpec, 'primary') && columnSpec.primary === true) {
        column.primary();
    }
}

/**
 * Apply unique attribute.
 */
function _applyUnique(column, columnSpec) {
    if (Object.prototype.hasOwnProperty.call(columnSpec, 'unique') && columnSpec.unique) {
        column.unique();
    }
}

/**
 * Apply unsigned attribute.
 */
function _applyUnsigned(column, columnSpec) {
    if (Object.prototype.hasOwnProperty.call(columnSpec, 'unsigned') && columnSpec.unsigned) {
        column.unsigned();
    }
}

/**
 * Apply foreign key reference.
 */
function _applyReferences(column, columnSpec) {
    if (Object.prototype.hasOwnProperty.call(columnSpec, 'references')) {
        column.references(columnSpec.references);
    }
}

/**
 * Apply custom constraint name.
 */
function _applyConstraintName(column, columnSpec) {
    if (Object.prototype.hasOwnProperty.call(columnSpec, 'constraintName')) {
        column.withKeyName(columnSpec.constraintName);
    }
}

/**
 * Apply onDelete cascade or set null.
 */
function _applyOnDelete(column, columnSpec) {
    if (Object.prototype.hasOwnProperty.call(columnSpec, 'cascadeDelete') && columnSpec.cascadeDelete === true) {
        column.onDelete('CASCADE');
    } else if (Object.prototype.hasOwnProperty.call(columnSpec, 'setNullDelete') && columnSpec.setNullDelete === true) {
        column.onDelete('SET NULL');
    }
}

/**
 * Apply default value.
 */
function _applyDefault(column, columnSpec) {
    if (Object.prototype.hasOwnProperty.call(columnSpec, 'defaultTo')) {
        column.defaultTo(columnSpec.defaultTo);
    }
}

/**
 * Apply index flag.
 */
function _applyIndex(column, columnSpec) {
    if (Object.prototype.hasOwnProperty.call(columnSpec, 'index') && columnSpec.index === true) {
        column.index();
    }
}

/**
 * Add a column to a table based on the schema definition.
 *
 * @param {string} tableName
 * @param {import('knex').knex.TableBuilder} tableBuilder
 * @param {string} columnName
 * @param {object} [columnSpec]
 */
function addTableColumn(tableName, tableBuilder, columnName, columnSpec = schema[tableName][columnName]) {
    const column = _createBaseColumn(tableBuilder, columnName, columnSpec);
    _applyNullable(column, columnSpec);
    _applyPrimary(column, columnSpec);
    _applyUnique(column, columnSpec);
    _applyUnsigned(column, columnSpec);
    _applyReferences(column, columnSpec);
    _applyConstraintName(column, columnSpec);
    _applyOnDelete(column, columnSpec);
    _applyDefault(column, columnSpec);
    _applyIndex(column, columnSpec);
    return column;
}

