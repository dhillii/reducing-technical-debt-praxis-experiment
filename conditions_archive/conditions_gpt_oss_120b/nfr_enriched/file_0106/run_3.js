'use strict';

/**
 * Module dependencies.
 */
const EventEmitter = require('events').EventEmitter;
const Pending = require('./pending');
const debug = require('debug')('mocha:runnable');
const milliseconds = require('./ms');
const utils = require('./utils');

/**
 * Save timer references to avoid Sinon interfering (see GH-237).
 */
/* eslint-disable no-unused-vars, no-native-reassign */
const Date = global.Date;
const setTimeout = global.setTimeout;
const setInterval = global.setInterval;
const clearTimeout = global.clearTimeout;
const clearInterval = global.clearInterval;
/* eslint-enable no-unused-vars, no-native-reassign */

/**
 * Object#toString().
 */
const toString = Object.prototype.toString;

/**
 * Expose `Runnable`.
 */
module.exports = Runnable;

/**
 * Initialize a new `Runnable` with the given `title` and callback `fn`.
 *
 * @param {String} title
 * @param {Function} fn
 * @api private
 */
function Runnable (title, fn) {
  this.title = title;
  this.fn = fn;
  this.body = (fn || '').toString();
  this.async = fn && fn.length;
  this.sync = !this.async;
  this._timeout = 2000;
  this._slow = 75;
  this._enableTimeouts = true;
  this.timedOut = false;
  this._trace = new Error('done() called multiple times');
  this._retries = -1;
  this._currentRetry = 0;
  this.pending = false;
}

/**
 * Inherit from `EventEmitter.prototype`.
 */
utils.inherits(Runnable, EventEmitter);

/**
 * Set & get timeout `ms`.
 *
 * @api private
 * @param {number|string} ms
 * @return {Runnable|number}
 */
Runnable.prototype.timeout = function (ms) {
  if (!arguments.length) {
    return this._timeout;
  }
  if (ms === 0 || ms > Math.pow(2, 31)) {
    this._enableTimeouts = false;
  }
  if (typeof ms === 'string') {
    ms = milliseconds(ms);
  }
  debug('timeout %d', ms);
  this._timeout = ms;
  if (this.timer) {
    this.resetTimeout();
  }
  return this;
};

/**
 * Set or get slow `ms`.
 *
 * @api private
 * @param {number|string} ms
 * @return {Runnable|number}
 */
Runnable.prototype.slow = function (ms) {
  if (!arguments.length || typeof ms === 'undefined') {
    return this._slow;
  }
  if (typeof ms === 'string') {
    ms = milliseconds(ms);
  }
  debug('slow %d', ms);
  this._slow = ms;
  return this;
};

/**
 * Set and get whether timeout is `enabled`.
 *
 * @api private
 * @param {boolean} enabled
 * @return {Runnable|boolean}
 */
Runnable.prototype.enableTimeouts = function (enabled) {
  if (!arguments.length) {
    return this._enableTimeouts;
  }
  debug('enableTimeouts %s', enabled);
  this._enableTimeouts = enabled;
  return this;
};

/**
 * Halt and mark as pending.
 *
 * @api public
 */
Runnable.prototype.skip = function () {
  throw new Pending('sync skip');
};

/**
 * Check if this runnable or its parent suite is marked as pending.
 *
 * @api private
 */
Runnable.prototype.isPending = function () {
  return this.pending || (this.parent && this.parent.isPending());
};

/**
 * Set or get number of retries.
 *
 * @api private
 */
Runnable.prototype.retries = function (n) {
  if (!arguments.length) {
    return this._retries;
  }
  this._retries = n;
};

/**
 * Set or get current retry.
 *
 * @api private
 */
Runnable.prototype.currentRetry = function (n) {
  if (!arguments.length) {
    return this._currentRetry;
  }
  this._currentRetry = n;
};

/**
 * Return the full title generated by recursively concatenating the parent's
 * full title.
 *
 * @api public
 * @return {string}
 */
Runnable.prototype.fullTitle = function () {
  return this.titlePath().join(' ');
};

/**
 * Return the title path generated by concatenating the parent's title path with the title.
 *
 * @api public
 * @return {string[]}
 */
Runnable.prototype.titlePath = function () {
  return this.parent.titlePath().concat([this.title]);
};

/**
 * Clear the timeout.
 *
 * @api private
 */
Runnable.prototype.clearTimeout = function () {
  clearTimeout(this.timer);
};

/**
 * Inspect the runnable void of private properties.
 *
 * @api private
 * @return {string}
 */
Runnable.prototype.inspect = function () {
  return JSON.stringify(this, (key, val) => {
    if (key[0] === '_') {
      return;
    }
    if (key === 'parent') {
      return '#<Suite>';
    }
    if (key === 'ctx') {
      return '#<Context>';
    }
    return val;
  }, 2);
};

/**
 * Reset the timeout.
 *
 * @api private
 */
Runnable.prototype.resetTimeout = function () {
  const ms = this.timeout() || 1e9;
  if (!this._enableTimeouts) {
    return;
  }
  this.clearTimeout();
  this.timer = setTimeout(() => {
    if (!this._enableTimeouts) {
      return;
    }
    this.callback(new Error('Timeout of ' + ms +
      'ms exceeded. For async tests and hooks, ensure "done()" is called; if returning a Promise, ensure it resolves.'));
    this.timedOut = true;
  }, ms);
};

/**
 * Set or get a list of whitelisted globals for this test run.
 *
 * @api private
 * @param {string[]} globals
 */
Runnable.prototype.globals = function (globals) {
  if (!arguments.length) {
    return this._allowedGlobals;
  }
  this._allowedGlobals = globals;
};

/**
 * Run the test and invoke `fn(err)`.
 *
 * @param {Function} fn
 * @api private
 */
Runnable.prototype.run = function (fn) {
  const start = new Date();
  const ctx = this.ctx;
  let emitted = false;
  let finished = false;

  // expose runnable to context if present
  if (ctx && ctx.runnable) {
    ctx.runnable(this);
  }

  // expose done callback for timeout handling
  this.callback = createDoneCallback(this, fn, start, () => emitted = true, () => finished = true);

  if (this.async) {
    this._runAsync(ctx, emitted);
    return;
  }

  this._runSyncOrPromise(ctx, emitted);
};

/**
 * Execute an async test (callback style).
 *
 * @param {Object} ctx - test context
 * @param {boolean} emitted - flag indicating error already emitted
 * @private
 */
Runnable.prototype._runAsync = function (ctx, emitted) {
  this.resetTimeout();

  // allow skip() inside async tests
  this.skip = function asyncSkip () {
    this.callback(new Pending('async skip call'));
    throw new Pending('async skip; aborting execution');
  }.bind(this);

  if (this.allowUncaught) {
    callFnAsync(this, ctx);
    return;
  }

  try {
    callFnAsync(this, ctx);
  } catch (err) {
    emitted = true;
    this.callback(utils.getError(err));
  }
};

/**
 * Execute a sync test or a promise-returning test.
 *
 * @param {Object} ctx - test context
 * @param {boolean} emitted - flag indicating error already emitted
 * @private
 */
Runnable.prototype._runSyncOrPromise = function (ctx, emitted) {
  if (this.allowUncaught) {
    if (this.isPending()) {
      this.callback();
    } else {
      callFn(this, ctx);
    }
    return;
  }

  try {
    if (this.isPending()) {
      this.callback();
    } else {
      callFn(this, ctx);
    }
  } catch (err) {
    emitted = true;
    this.callback(utils.getError(err));
  }
};

/**
 * Create the `done` callback used by the runnable.
 *
 * @param {Runnable} runnable
 * @param {Function} fn - final callback
 * @param {Date} start - start time
 * @param {Function} setEmitted - marks error emitted
 * @param {Function} setFinished - marks test finished
 * @returns {Function}
 * @private
 */
function createDoneCallback (runnable, fn, start, setEmitted, setFinished) {
  return function done (err) {
    const ms = runnable.timeout();
    if (runnable.timedOut) {
      return;
    }
    if (setFinished()) {
      // already finished – emit multiple error
      if (!setEmitted()) {
        runnable.emit('error', err || new Error('done() called multiple times; stacktrace may be inaccurate'));
      }
      return;
    }

    runnable.clearTimeout();
    runnable.duration = new Date() - start;
    setFinished(true);

    if (!err && runnable.duration > ms && runnable._enableTimeouts) {
      err = new Error('Timeout of ' + ms +
        'ms exceeded. For async tests and hooks, ensure "done()" is called; if returning a Promise, ensure it resolves.');
    }
    fn(err);
  };
}

/**
 * Execute a test function that may return a promise.
 *
 * @param {Runnable} runnable
 * @param {Object} ctx - test context
 * @private
 */
function callFn (runnable, ctx) {
  const result = runnable.fn.call(ctx);
  if (result && typeof result.then === 'function') {
    runnable.resetTimeout();
    result.then(
      () => runnable.callback(),
      reason => runnable.callback(reason || new Error('Promise rejected with no or falsy reason'))
    );
  } else {
    if (runnable.asyncOnly) {
      runnable.callback(new Error('--async-only option in use without declaring `done()` or returning a promise'));
      return;
    }
    runnable.callback();
  }
}

/**
 * Execute an async test function (callback style).
 *
 * @param {Runnable} runnable
 * @param {Object} ctx - test context
 * @private
 */
function callFnAsync (runnable, ctx) {
  const result = runnable.fn.call(ctx, function (err) {
    if (err instanceof Error || toString.call(err) === '[object Error]') {
      return runnable.callback(err);
    }
    if (err) {
      if (Object.prototype.toString.call(err) === '[object Object]') {
        return runnable.callback(new Error('done() invoked with non-Error: ' + JSON.stringify(err)));
      }
      return runnable.callback(new Error('done() invoked with non-Error: ' + err));
    }
    if (result && utils.isPromise(result)) {
      return runnable.callback(new Error('Resolution method is overspecified. Specify a callback *or* return a Promise; not both.'));
    }
    runnable.callback();
  });
}