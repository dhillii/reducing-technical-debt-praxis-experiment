/**
 * Return the full title generated by recursively concatenating the parent's
 * full title.
 *
 * @return {string}
 * @api public
 */
Runnable.prototype.fullTitle = function () {
  return this.titlePath().join(' ');
};

/**
 * Return the title path generated by concatenating the parent's title path with the title.
 *
 * @return {string}
 * @api public
 */
Runnable.prototype.titlePath = function () {
  return this.parent.titlePath().concat([this.title]);
};

/**
 * Clear the timeout.
 *
 * @api private
 */
Runnable.prototype.clearTimeout = function () {
  clearTimeout(this.timer);
};

/**
 * Inspect the runnable void of private properties.
 *
 * @return {string}
 * @api private
 */
Runnable.prototype.inspect = function () {
  return JSON.stringify(this, function (key, val) {
    if (key[0] === '_') {
      return;
    }
    if (key === 'parent') {
      return '#<Suite>';
    }
    if (key === 'ctx') {
      return '#<Context>';
    }
    return val;
  }, 2);
};

/**
 * Reset the timeout.
 *
 * @api private
 */
Runnable.prototype.resetTimeout = function () {
  var self = this;
  var ms = this.timeout() || 1e9;

  if (!this._enableTimeouts) {
    return;
  }
  this.clearTimeout();
  this.timer = setTimeout(function () {
    if (!self._enableTimeouts) {
      return;
    }
    self.callback(new Error('Timeout of ' + ms +
      'ms exceeded. For async tests and hooks, ensure "done()" is called; if returning a Promise, ensure it resolves.'));
    self.timedOut = true;
  }, ms);
};

/**
 * Set or get a list of whitelisted globals for this test run.
 *
 * @param {string[]} globals
 * @return {string[]|Runnable}
 * @api private
 */
Runnable.prototype.globals = function (globals) {
  if (!arguments.length) {
    return this._allowedGlobals;
  }
  this._allowedGlobals = globals;
  return this;
};

/**
 * Run the test and invoke `fn(err)`.
 *
 * @param {Function} fn
 * @api private
 */
Runnable.prototype.run = function (fn) {
  var self = this;
  var start = new Date();
  var ctx = this.ctx;
  var finished;
  var emitted;

  if (ctx && ctx.runnable) {
    ctx.runnable(this);
  }

  function multiple (err) {
    if (emitted) {
      return;
    }
    emitted = true;
    self.emit('error', err || new Error('done() called multiple times; stacktrace may be inaccurate'));
  }

  function done (err) {
    var ms = self.timeout();
    if (self.timedOut) {
      return;
    }
    if (finished) {
      return multiple(err || self._trace);
    }

    self.clearTimeout();
    self.duration = new Date() - start;
    finished = true;
    if (!err && self.duration > ms && self._enableTimeouts) {
      err = new Error('Timeout of ' + ms +
      'ms exceeded. For async tests and hooks, ensure "done()" is called; if returning a Promise, ensure it resolves.');
    }
    fn(err);
  }

  this.callback = done;

  if (this.async) {
    handleAsync.call(this, fn, done, multiple, emitted);
    return;
  }

  if (this.allowUncaught) {
    handleSyncAllowUncaught.call(this, done);
    return;
  }

  handleSync.call(this, done);
};

/**
 * Handle async runnable execution.
 * @param {Function} fn - final callback
 * @param {Function} done - internal done handler
 * @param {Function} multiple - duplicate call guard
 * @param {boolean} emitted - flag tracking error emission
 * @private
 */
function handleAsync (fn, done, multiple, emitted) {
  var self = this;

  this.resetTimeout();

  this.skip = function asyncSkip () {
    done(new Pending('async skip call'));
    throw new Pending('async skip; aborting execution');
  };

  if (this.allowUncaught) {
    callFnAsync.call(this, this.fn);
    return;
  }

  try {
    callFnAsync.call(this, this.fn);
  } catch (err) {
    emitted = true;
    done(utils.getError(err));
  }
}

/**
 * Handle synchronous runnable with allowUncaught enabled.
 * @param {Function} done - internal done handler
 * @private
 */
function handleSyncAllowUncaught (done) {
  if (this.isPending()) {
    done();
  } else {
    callFn.call(this, this.fn);
  }
}

/**
 * Handle synchronous runnable execution with error handling.
 * @param {Function} done - internal done handler
 * @private
 */
function handleSync (done) {
  try {
    if (this.isPending()) {
      done();
    } else {
      callFn.call(this, this.fn);
    }
  } catch (err) {
    this._emitted = true;
    done(utils.getError(err));
  }
}

/**
 * Execute a synchronous/test function with Promise detection.
 * @param {Function} fn - the test function to execute
 * @private
 */
function callFn (fn) {
  var result = fn.call(this.ctx);
  if (result && typeof result.then === 'function') {
    this.resetTimeout();
    result
      .then(function () {
        done.call(this);
        return null;
      }.bind(this),
      function (reason) {
        done.call(this, reason || new Error('Promise rejected with no or falsy reason'));
      }.bind(this));
  } else {
    if (this.asyncOnly) {
      done.call(this, new Error('--async-only option in use without declaring `done()` or returning a promise'));
    } else {
      done.call(this);
    }
  }
}

/**
 * Execute an asynchronous/test function with callback.
 * @param {Function} fn - the async test function
 * @private
 */
function callFnAsync (fn) {
  var self = this;
  var result;

  try {
    result = fn.call(this.ctx, function (err) {
      if (err instanceof Error || toString.call(err) === '[object Error]') {
        return done.call(self, err);
      }
      if (err) {
        if (Object.prototype.toString.call(err) === '[object Object]') {
          return done.call(self, new Error('done() invoked with non-Error: ' +
            JSON.stringify(err)));
        }
        return done.call(self, new Error('done() invoked with non-Error: ' + err));
      }
      if (result && utils.isPromise(result)) {
        return done.call(self, new Error('Resolution method is overspecified. Specify a callback *or* return a Promise; not both.'));
      }

      done.call(self);
    });
  } catch (e) {
    done.call(self, e);
  }
}