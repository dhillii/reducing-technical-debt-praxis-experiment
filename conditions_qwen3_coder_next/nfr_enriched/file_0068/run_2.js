/**
 * Creates a rule entry mapping function for a given rule name and module path.
 * @param {string} ruleName The name of the ESLint rule.
 * @param {string} modulePath The relative path to the rule module.
 * @returns {[string, () => import("../types").Rule.RuleModule]} A tuple of rule name and lazy loader.
 */
function createRuleEntry(ruleName, modulePath) {
	return [ruleName, () => require(modulePath)];
}

