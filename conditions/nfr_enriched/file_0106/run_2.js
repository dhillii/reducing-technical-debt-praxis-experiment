/**
 * Module dependencies.
 */

const EventEmitter = require('events').EventEmitter;
const Pending = require('./pending');
const debug = require('debug')('mocha:runnable');
const milliseconds = require('./ms');
const utils = require('./utils');

/**
 * Save timer references to avoid Sinon interfering (see GH-237).
 */

/* eslint-disable no-unused-vars, no-native-reassign */
const Date = global.Date;
const setTimeout = global.setTimeout;
const setInterval = global.setInterval;
const clearTimeout = global.clearTimeout;
const clearInterval = global.clearInterval;
/* eslint-enable no-unused-vars, no-native-reassign */

/**
 * Object#toString().
 */

const toString = Object.prototype.toString;

/**
 * Expose `Runnable`.
 */

module.exports = Runnable;

/**
 * Initialize a new `Runnable` with the given `title` and callback `fn`.
 *
 * @param {String} title
 * @param {Function} fn
 * @api private
 */
function Runnable (title, fn) {
  this.title = title;
  this.fn = fn;
  this.body = (fn || '').toString();
  this.async = fn && fn.length;
  this.sync = !this.async;
  this._timeout = 2000;
  this._slow = 75;
  this._enableTimeouts = true;
  this.timedOut = false;
  this._trace = new Error('done() called multiple times');
  this._retries = -1;
  this._currentRetry = 0;
  this.pending = false;
}

/**
 * Inherit from `EventEmitter.prototype`.
 */
utils.inherits(Runnable, EventEmitter);

/**
 * Set & get timeout `ms`.
 *
 * @api private
 * @param {number|string} ms
 * @return {Runnable|number} ms or Runnable instance.
 */
Runnable.prototype.timeout = function (ms) {
  if (!arguments.length) {
    return this._timeout;
  }
  // see #1652 for reasoning
  if (ms === 0 || ms > Math.pow(2, 31)) {
    this._enableTimeouts = false;
  }
  if (typeof ms === 'string') {
    ms = milliseconds(ms);
  }
  debug('timeout %d', ms);
  this._timeout = ms;
  if (this.timer) {
    this.resetTimeout();
  }
  return this;
};

/**
 * Set or get slow `ms`.
 *
 * @api private
 * @param {number|string} ms
 * @return {Runnable|number} ms or Runnable instance.
 */
Runnable.prototype.slow = function (ms) {
  if (!arguments.length || typeof ms === 'undefined') {
    return this._slow;
  }
  if (typeof ms === 'string') {
    ms = milliseconds(ms);
  }
  debug('timeout %d', ms);
  this._slow = ms;
  return this;
};

/**
 * Set and get whether timeout is `enabled`.
 *
 * @api private
 * @param {boolean} enabled
 * @return {Runnable|boolean} enabled or Runnable instance.
 */
Runnable.prototype.enableTimeouts = function (enabled) {
  if (!arguments.length) {
    return this._enableTimeouts;
  }
  debug('enableTimeouts %s', enabled);
  this._enableTimeouts = enabled;
  return this;
};

/**
 * Halt and mark as pending.
 *
 * @api public
 */
Runnable.prototype.skip = function () {
  throw new Pending('sync skip');
};

/**
 * Check if this runnable or its parent suite is marked as pending.
 *
 * @api private
 */
Runnable.prototype.isPending = function () {
  return this.pending || (this.parent && this.parent.isPending());
};

/**
 * Set or get number of retries.
 *
 * @api private
 */
Runnable.prototype.retries = function (n) {
  if (!arguments.length) {
    return this._retries;
  }
  this._retries = n;
};

/**
 * Set or get current retry
 *
 * @api private
 */
Runnable.prototype.currentRetry = function (n) {
  if (!arguments.length) {
    return this._currentRetry;
  }
  this._currentRetry = n;
};

/**
 * Return the full title generated by recursively concatenating the parent's
 * full title.
 *
 * @api public
 * @return {string}
 */
Runnable.prototype.fullTitle = function () {
  return this.titlePath().join(' ');
};

/**
 * Return the title path generated by concatenating the parent's title path with the title.
 *
 * @api public
 * @return {string}
 */
Runnable.prototype.titlePath = function () {
  return this.parent.titlePath().concat([this.title]);
};

/**
 * Clear the timeout.
 *
 * @api private
 */
Runnable.prototype.clearTimeout = function () {
  clearTimeout(this.timer);
};

/**
 * Inspect the runnable void of private properties.
 *
 * @api private
 * @return {string}
 */
Runnable.prototype.inspect = function () {
  return JSON.stringify(this, function (key, val) {
    if (key[0] === '_') {
      return;
    }
    if (key === 'parent') {
      return '#<Suite>';
    }
    if (key === 'ctx') {
      return '#<Context>';
    }
    return val;
  }, 2);
};

/**
 * Reset the timeout.
 *
 * @api private
 */
Runnable.prototype.resetTimeout = function () {
  const self = this;
  const ms = this.timeout() || 1e9;

  if (!this._enableTimeouts) {
    return;
  }
  this.clearTimeout();
  this.timer = setTimeout(function () {
    if (!self._enableTimeouts) {
      return;
    }
    self.callback(new Error('Timeout of ' + ms +
      'ms exceeded. For async tests and hooks, ensure "done()" is called; if returning a Promise, ensure it resolves.'));
    self.timedOut = true;
  }, ms);
};

/**
 * Set or get a list of whitelisted globals for this test run.
 *
 * @api private
 * @param {string[]} globals
 */
Runnable.prototype.globals = function (globals) {
  if (!arguments.length) {
    return this._allowedGlobals;
  }
  this._allowedGlobals = globals;
};

/**
 * Handle multiple calls to done callback.
 *
 * @api private
 * @param {Error} err
 * @param {boolean} emitted
 * @param {Function} self
 */
function handleMultipleDone (err, emitted, self) {
  if (emitted) {
    return;
  }
  self.emit('error', err || new Error('done() called multiple times; stacktrace may be inaccurate'));
}

/**
 * Create the done callback for test execution.
 *
 * @api private
 * @param {Runnable} self
 * @param {Date} start
 * @param {Function} fn
 * @return {Function}
 */
function createDoneCallback (self, start, fn) {
  let finished = false;
  let emitted = false;

  return function done (err) {
    const ms = self.timeout();
    if (self.timedOut) {
      return;
    }
    if (finished) {
      handleMultipleDone(err || self._trace, emitted, self);
      emitted = true;
      return;
    }

    self.clearTimeout();
    self.duration = new Date() - start;
    finished = true;
    if (!err && self.duration > ms && self._enableTimeouts) {
      err = new Error('Timeout of ' + ms +
      'ms exceeded. For async tests and hooks, ensure "done()" is called; if returning a Promise, ensure it resolves.');
    }
    fn(err);
  };
}

/**
 * Create async skip function for explicit async context.
 *
 * @api private
 * @param {Function} done
 * @return {Function}
 */
function createAsyncSkip (done) {
  return function asyncSkip () {
    done(new Pending('async skip call'));
    throw new Pending('async skip; aborting execution');
  };
}

/**
 * Execute function with context and handle promise result.
 *
 * @api private
 * @param {Function} fn
 * @param {Object} ctx
 * @param {Function} done
 * @param {Runnable} self
 */
function callFn (fn, ctx, done, self) {
  const result = fn.call(ctx);
  if (result && typeof result.then === 'function') {
    self.resetTimeout();
    result
      .then(function () {
        done();
        return null;
      },
      function (reason) {
        done(reason || new Error('Promise rejected with no or falsy reason'));
      });
  } else {
    if (self.asyncOnly) {
      return done(new Error('--async-only option in use without declaring `done()` or returning a promise'));
    }
    done();
  }
}

/**
 * Execute async function with done callback.
 *
 * @api private
 * @param {Function} fn
 * @param {Object} ctx
 * @param {Function} done
 */
function callFnAsync (fn, ctx, done) {
  const result = fn.call(ctx, function (err) {
    if (err instanceof Error || toString.call(err) === '[object Error]') {
      return done(err);
    }
    if (err) {
      if (Object.prototype.toString.call(err) === '[object Object]') {
        return done(new Error('done() invoked with non-Error: ' +
          JSON.stringify(err)));
      }
      return done(new Error('done() invoked with non-Error: ' + err));
    }
    if (result && utils.isPromise(result)) {
      return done(new Error('Resolution method is overspecified. Specify a callback *or* return a Promise; not both.'));
    }

    done();
  });
}

/**
 * Execute synchronous test with error handling.
 *
 * @api private
 * @param {Runnable} self
 * @param {Function} done
 */
function executeSyncTest (self, done) {
  try {
    if (self.isPending()) {
      done();
    } else {
      callFn(self.fn, self.ctx, done, self);
    }
  } catch (err) {
    done(utils.getError(err));
  }
}

/**
 * Execute asynchronous test with error handling.
 *
 * @api private
 * @param {Runnable} self
 * @param {Function} done
 */
function executeAsyncTest (self, done) {
  self.resetTimeout();
  self.skip = createAsyncSkip(done);

  if (self.allowUncaught) {
    return callFnAsync(self.fn, self.ctx, done);
  }
  try {
    callFnAsync(self.fn, self.ctx, done);
  } catch (err) {
    done(utils.getError(err));
  }
}

/**
 * Execute test allowing uncaught exceptions.
 *
 * @api private
 * @param {Runnable} self
 * @param {Function} done
 */
function executeUncaughtTest (self, done) {
  if (self.isPending()) {
    done();
  } else {
    callFn(self.fn, self.ctx, done, self);
  }
}

/**
 * Run the test and invoke `fn(err)`.
 *
 * @param {Function} fn
 * @api private
 */
Runnable.prototype.run = function (fn) {
  const self = this;
  const start = new Date();
  const ctx = this.ctx;

  // Sometimes the ctx exists, but it is not runnable
  if (ctx && ctx.runnable) {
    ctx.runnable(this);
  }

  const done = createDoneCallback(this, start, fn);

  // for .resetTimeout()
  this.callback = done;

  // explicit async with `done` argument
  if (this.async) {
    executeAsyncTest(this, done);
    return;
  }

  if (this.allowUncaught) {
    executeUncaughtTest(this, done);
    return;
  }

  // sync or promise-returning
  executeSyncTest(this, done);
};