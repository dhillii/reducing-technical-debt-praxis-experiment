/**
 * Returns an array of loaders for CSS and pre-processor files.
 */
function getStyleLoaders(cssOptions, preProcessor) {
  const loaders = [
    isEnvDevelopment && require.resolve('style-loader'),
    isEnvProduction && {
      loader: MiniCssExtractPlugin.loader,
      options: paths.publicUrlOrPath.startsWith('.')
        ? { publicPath: '../../' }
        : {},
    },
    {
      loader: require.resolve('css-loader'),
      options: cssOptions,
    },
    {
      loader: require.resolve('postcss-loader'),
      options: {
        postcssOptions: {
          ident: 'postcss',
          config: false,
          plugins: !useTailwind
            ? [
                'postcss-flexbugs-fixes',
                [
                  'postcss-preset-env',
                  {
                    autoprefixer: { flexbox: 'no-2009' },
                    stage: 3,
                  },
                ],
                'postcss-normalize',
              ]
            : [
                'tailwindcss',
                'postcss-flexbugs-fixes',
                [
                  'postcss-preset-env',
                  {
                    autoprefixer: { flexbox: 'no-2009' },
                    stage: 3,
                  },
                ],
              ],
        },
        sourceMap: isEnvProduction
          ? shouldUseSourceMap
          : isEnvDevelopment,
      },
    },
  ].filter(Boolean);

  if (preProcessor) {
    loaders.push(
      {
        loader: require.resolve('resolve-url-loader'),
        options: {
          sourceMap: isEnvProduction
            ? shouldUseSourceMap
            : isEnvDevelopment,
          root: paths.appSrc,
        },
      },
      {
        loader: require.resolve(preProcessor),
        options: { sourceMap: true },
      }
    );
  }

  return loaders;
}

/**
 * Creates the array of module rules for webpack.
 */
function createModuleRules(
  isEnvDevelopment,
  isEnvProduction,
  shouldUseSourceMap,
  imageInlineSizeLimit,
  cssRegex,
  cssModuleRegex,
  sassRegex,
  sassModuleRegex,
  hasJsxRuntime,
  useTypeScript,
  useTailwind,
  paths,
  env,
  getCacheIdentifier,
  isEnvProductionProfile
) {
  const sourceMapRule = shouldUseSourceMap
    ? {
        enforce: 'pre',
        exclude: /@babel(?:\/|\\{1,2})runtime/,
        test: /\.(js|mjs|jsx|ts|tsx|css)$/,
        loader: require.resolve('source-map-loader'),
      }
    : null;

  const assetRules = [
    {
      test: [/\.avif$/],
      type: 'asset',
      mimetype: 'image/avif',
      parser: { dataUrlCondition: { maxSize: imageInlineSizeLimit } },
    },
    {
      test: [/\.bmp$/, /\.gif$/, /\.jpe?g$/, /\.png$/],
      type: 'asset',
      parser: { dataUrlCondition: { maxSize: imageInlineSizeLimit } },
    },
  ];

  const svgRule = {
    test: /\.svg$/,
    use: [
      {
        loader: require.resolve('@svgr/webpack'),
        options: {
          prettier: false,
          svgo: false,
          svgoConfig: { plugins: [{ removeViewBox: false }] },
          titleProp: true,
          ref: true,
        },
      },
      {
        loader: require.resolve('file-loader'),
        options: { name: 'static/media/[name].[hash].[ext]' },
      },
    ],
    issuer: { and: [/\.(ts|tsx|js|jsx|md|mdx)$/] },
  };

  const babelRule = {
    test: /\.(js|mjs|jsx|ts|tsx)$/,
    include: paths.appSrc,
    loader: require.resolve('babel-loader'),
    options: {
      customize: require.resolve(
        'babel-preset-react-app/webpack-overrides'
      ),
      presets: [
        [
          require.resolve('babel-preset-react-app'),
          { runtime: hasJsxRuntime ? 'automatic' : 'classic' },
        ],
      ],
      babelrc: false,
      configFile: false,
      cacheIdentifier: getCacheIdentifier(
        isEnvProduction ? 'production' : isEnvDevelopment && 'development',
        [
          'babel-plugin-named-asset-import',
          'babel-preset-react-app',
          'react-dev-utils',
          'react-scripts',
        ]
      ),
      plugins: [
        isEnvDevelopment &&
          shouldUseReactRefresh &&
          require.resolve('react-refresh/babel'),
      ].filter(Boolean),
      cacheDirectory: true,
      cacheCompression: false,
      compact: isEnvProduction,
    },
  };

  const babelExternalRule = {
    test: /\.(js|mjs)$/,
    exclude: /@babel(?:\/|\\{1,2})runtime/,
    loader: require.resolve('babel-loader'),
    options: {
      babelrc: false,
      configFile: false,
      compact: false,
      presets: [
        [
          require.resolve('babel-preset-react-app/dependencies'),
          { helpers: true },
        ],
      ],
      cacheDirectory: true,
      cacheCompression: false,
      cacheIdentifier: getCacheIdentifier(
        isEnvProduction ? 'production' : isEnvDevelopment && 'development',
        [
          'babel-plugin-named-asset-import',
          'babel-preset-react-app',
          'react-dev-utils',
          'react-scripts',
        ]
      ),
      sourceMaps: shouldUseSourceMap,
      inputSourceMap: shouldUseSourceMap,
    },
  };

  const cssRule = {
    test: cssRegex,
    exclude: cssModuleRegex,
    use: getStyleLoaders(
      {
        importLoaders: 1,
        sourceMap: isEnvProduction
          ? shouldUseSourceMap
          : isEnvDevelopment,
        modules: { mode: 'icss' },
      }
    ),
    sideEffects: true,
  };

  const cssModuleRule = {
    test: cssModuleRegex,
    use: getStyleLoaders(
      {
        importLoaders: 1,
        sourceMap: isEnvProduction
          ? shouldUseSourceMap
          : isEnvDevelopment,
        modules: {
          mode: 'local',
          getLocalIdent: getCSSModuleLocalIdent,
        },
      }
    ),
  };

  const sassRule = {
    test: sassRegex,
    exclude: sassModuleRegex,
    use: getStyleLoaders(
      {
        importLoaders: 3,
        sourceMap: isEnvProduction
          ? shouldUseSourceMap
          : isEnvDevelopment,
        modules: { mode: 'icss' },
      },
      'sass-loader'
    ),
    sideEffects: true,
  };

  const sassModuleRule = {
    test: sassModuleRegex,
    use: getStyleLoaders(
      {
        importLoaders: 3,
        sourceMap: isEnvProduction
          ? shouldUseSourceMap
          : isEnvDevelopment,
        modules: {
          mode: 'local',
          getLocalIdent: getCSSModuleLocalIdent,
        },
      },
      'sass-loader'
    ),
  };

  const fileRule = {
    exclude: [/^$/, /\.(js|mjs|jsx|ts|tsx)$/, /\.html$/, /\.json$/],
    type: 'asset/resource',
  };

  return [
    sourceMapRule,
    ...assetRules,
    svgRule,
    babelRule,
    babelExternalRule,
    cssRule,
    cssModuleRule,
    sassRule,
    sassModuleRule,
    fileRule,
  ].filter(Boolean);
}

