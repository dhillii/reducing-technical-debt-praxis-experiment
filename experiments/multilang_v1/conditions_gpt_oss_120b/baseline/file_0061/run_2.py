class AdminScriptTestCase(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        super(AdminScriptTestCase, cls).setUpClass()
        cls.test_dir = os.path.realpath(
            os.path.join(tempfile.gettempdir(), cls.__name__, 'test_project')
        )
        os.makedirs(cls.test_dir, exist_ok=True)
        open(os.path.join(cls.test_dir, '__init__.py'), 'w').close()

    @classmethod
    def tearDownClass(cls):
        shutil.rmtree(cls.test_dir)
        super(AdminScriptTestCase, cls).tearDownClass()

    # --------------------------------------------------------------------- #
    # Settings file helpers
    # --------------------------------------------------------------------- #
    def write_settings(self, filename, apps=None, is_dir=False, sdict=None, extra=None):
        settings_path = self._prepare_settings_path(filename, is_dir)
        content = self._generate_settings_content(apps, sdict, extra)
        with open(settings_path, 'w') as fp:
            fp.write(content)

    def _prepare_settings_path(self, filename, is_dir):
        if is_dir:
            dir_path = os.path.join(self.test_dir, filename)
            os.mkdir(dir_path)
            return os.path.join(dir_path, '__init__.py')
        return os.path.join(self.test_dir, filename)

    def _generate_settings_content(self, apps, sdict, extra):
        lines = [
            '# -*- coding: utf-8 -*-\n',
            '# Settings file automatically generated by admin_scripts test case\n',
        ]
        if extra:
            lines.append(f"{extra}\n")
        exports = ['DATABASES', 'ROOT_URLCONF', 'SECRET_KEY']
        for name in exports:
            if hasattr(settings, name):
                value = getattr(settings, name)
                if not isinstance(value, (dict, tuple, list)):
                    value = f"'{value}'"
                lines.append(f"{name} = {value}\n")
        if apps is None:
            apps = ['django.contrib.auth', 'django.contrib.contenttypes', 'admin_scripts']
        lines.append(f"INSTALLED_APPS = {apps}\n")
        if sdict:
            for k, v in sdict.items():
                lines.append(f"{k} = {v}\n")
        return ''.join(lines)

    def remove_settings(self, filename, is_dir=False):
        target = os.path.join(self.test_dir, filename)
        if is_dir:
            shutil.rmtree(target)
        else:
            os.remove(target)
        self._cleanup_compiled_files(target)
        self._cleanup_pycache()

    def _cleanup_compiled_files(self, base_path):
        try:
            if sys.platform.startswith('java'):
                os.remove(re.sub(r'\.py$', '$py.class', base_path))
            else:
                os.remove(base_path + 'c')
        except OSError:
            pass

    def _cleanup_pycache(self):
        cache_dir = os.path.join(self.test_dir, '__pycache__')
        if os.path.isdir(cache_dir):
            shutil.rmtree(cache_dir)

    # --------------------------------------------------------------------- #
    # Backend path helpers
    # --------------------------------------------------------------------- #
    def _ext_backend_paths(self):
        paths = []
        for backend in settings.DATABASES.values():
            package = backend['ENGINE'].split('.')[0]
            if package != 'django':
                backend_pkg = __import__(package)
                backend_dir = os.path.dirname(backend_pkg.__file__)
                paths.append(os.path.dirname(backend_dir))
        return paths

    # --------------------------------------------------------------------- #
    # Test execution helpers
    # --------------------------------------------------------------------- #
    def run_test(self, script, args, settings_file=None, apps=None):
        env = self._build_test_environment(settings_file)
        cwd = os.getcwd()
        os.chdir(self.test_dir)
        try:
            out, err = self._execute_subprocess(script, args, env)
        finally:
            os.chdir(cwd)
        return out, err

    def _build_test_environment(self, settings_file):
        env = os.environ.copy()
        python_path_var = 'JYTHONPATH' if sys.platform.startswith('java') else 'PYTHONPATH'
        base_dir = os.path.dirname(self.test_dir)
        tests_dir = os.path.dirname(os.path.dirname(upath(__file__)))
        django_dir = os.path.dirname(tests_dir)
        paths = [base_dir, django_dir, tests_dir] + self._ext_backend_paths()
        env[python_path_var] = npath(os.pathsep.join(paths))
        env['PYTHONWARNINGS'] = ''
        if settings_file:
            env['DJANGO_SETTINGS_MODULE'] = str(settings_file)
        else:
            env.pop('DJANGO_SETTINGS_MODULE', None)
        return env

    def _execute_subprocess(self, script, args, env):
        process = subprocess.Popen(
            [sys.executable, script] + args,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            env=env,
            universal_newlines=True,
        )
        return process.communicate()

    def run_django_admin(self, args, settings_file=None):
        script_dir = os.path.abspath(
            os.path.join(os.path.dirname(upath(django.__file__)), 'bin')
        )
        return self.run_test(os.path.join(script_dir, 'django-admin.py'), args, settings_file)

    def run_manage(self, args, settings_file=None):
        manage_path = self._prepare_manage_script()
        self.addCleanup(os.remove, manage_path)
        return self.run_test(manage_path, args, settings_file)

    def _prepare_manage_script(self):
        conf_dir = os.path.dirname(upath(conf.__file__))
        template_path = os.path.join(conf_dir, 'project_template', 'manage.py-tpl')
        target_path = os.path.join(self.test_dir, 'manage.py')
        shutil.copyfile(template_path, target_path)
        with open(target_path, 'r') as fp:
            content = fp.read()
        content = content.replace("{{ project_name }}", "test_project")
        with open(target_path, 'w') as fp:
            fp.write(content)
        return target_path

    # --------------------------------------------------------------------- #
    # Assertion helpers
    # --------------------------------------------------------------------- #
    def assertNoOutput(self, stream):
        self.assertEqual(len(stream), 0, f"Stream should be empty: actually contains '{stream}'")

    def assertOutput(self, stream, msg, regex=False):
        stream = force_text(stream)
        if regex:
            self.assertIsNotNone(
                re.search(msg, stream),
                f"'{msg}' does not match actual output text '{stream}'"
            )
        else:
            self.assertIn(msg, stream, f"'{msg}' does not match actual output text '{stream}'")

    def assertNotInOutput(self, stream, msg):
        stream = force_text(stream)
        self.assertNotIn(msg, stream, f"'{msg}' matches actual output text '{stream}'")


