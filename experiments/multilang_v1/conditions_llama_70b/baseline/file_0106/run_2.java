public PiePlot(PiePlot plot) {
    this.dataset = plot.dataset;
    this.pieIndex = plot.pieIndex;
    this.interiorGap = plot.interiorGap;
    this.circular = plot.circular;
    this.startAngle = plot.startAngle;
    this.direction = plot.direction;
    this.minimumArcAngleToDraw = plot.minimumArcAngleToDraw;
    this.sectionPaintMap = (PaintMap) plot.sectionPaintMap.clone();
    this.baseSectionPaint = plot.baseSectionPaint;
    this.autoPopulateSectionPaint = plot.autoPopulateSectionPaint;
    this.sectionOutlinesVisible = plot.sectionOutlinesVisible;
    this.sectionOutlinePaintMap = (PaintMap) plot.sectionOutlinePaintMap.clone();
    this.baseSectionOutlinePaint = plot.baseSectionOutlinePaint;
    this.autoPopulateSectionOutlinePaint = plot.autoPopulateSectionOutlinePaint;
    this.sectionOutlineStrokeMap = (StrokeMap) plot.sectionOutlineStrokeMap.clone();
    this.baseSectionOutlineStroke = plot.baseSectionOutlineStroke;
    this.autoPopulateSectionOutlineStroke = plot.autoPopulateSectionOutlineStroke;
    this.explodePercentages = new TreeMap<>(plot.explodePercentages);
    this.labelGenerator = plot.labelGenerator;
    this.labelFont = plot.labelFont;
    this.labelPaint = plot.labelPaint;
    this.labelBackgroundPaint = plot.labelBackgroundPaint;
    this.labelOutlinePaint = plot.labelOutlinePaint;
    this.labelOutlineStroke = plot.labelOutlineStroke;
    this.labelShadowPaint = plot.labelShadowPaint;
    this.simpleLabels = plot.simpleLabels;
    this.simpleLabelOffset = plot.simpleLabelOffset;
    this.labelPadding = plot.labelPadding;
    this.maximumLabelWidth = plot.maximumLabelWidth;
    this.labelGap = plot.labelGap;
    this.labelLinksVisible = plot.labelLinksVisible;
    this.labelLinkStyle = plot.labelLinkStyle;
    this.labelLinkMargin = plot.labelLinkMargin;
    this.labelLinkPaint = plot.labelLinkPaint;
    this.labelLinkStroke = plot.labelLinkStroke;
    this.labelDistributor = plot.labelDistributor;
    this.toolTipGenerator = plot.toolTipGenerator;
    this.urlGenerator = plot.urlGenerator;
    this.legendLabelGenerator = plot.legendLabelGenerator;
    this.legendLabelToolTipGenerator = plot.legendLabelToolTipGenerator;
    this.legendLabelURLGenerator = plot.legendLabelURLGenerator;
    this.legendItemShape = plot.legendItemShape;
    this.ignoreNullValues = plot.ignoreNullValues;
    this.ignoreZeroValues = plot.ignoreZeroValues;
    this.shadowGenerator = plot.shadowGenerator;
}