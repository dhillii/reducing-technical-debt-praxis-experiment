/**
 * Creates a map of all built-in ESLint rules.
 * @returns {import("./utils/lazy-loading-rule-map").LazyLoadingRuleMap} The rule map.
 */
function createRuleMap() {
	const ruleMap = new LazyLoadingRuleMap();

	for (const [ruleName, ruleModule] of Object.entries(getRuleModule)) {
		ruleMap.set(ruleName, ruleModule);
	}

	return ruleMap;
}

